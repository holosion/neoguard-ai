"""Rebuild original embedded icons and an illustrative screen preview (Pillow)."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent
icons = {}
for name in ('heart', 'temperature', 'oxygen', 'storage', 'clock'):
    im = Image.new('1', (32, 32))
    d = ImageDraw.Draw(im)
    if name == 'heart':
        d.ellipse((2, 4, 16, 18), fill=1)
        d.ellipse((15, 4, 29, 18), fill=1)
        d.polygon([(3, 13), (28, 13), (16, 29)], fill=1)
    elif name == 'temperature':
        d.rounded_rectangle((12, 2, 20, 23), radius=4, outline=1, width=2)
        d.ellipse((8, 17, 24, 31), fill=1)
        d.line((16, 8, 16, 24), fill=1, width=3)
        for y in (6, 11, 16):
            d.line((23, y, 27, y), fill=1, width=2)
    elif name == 'oxygen':
        d.polygon([(16, 1), (5, 16), (27, 16)], fill=1)
        d.ellipse((4, 10, 28, 31), fill=1)
        d.arc((8, 15, 23, 27), 60, 160, fill=0, width=2)
    elif name == 'storage':
        d.polygon([(6, 1), (23, 1), (28, 6), (28, 30), (4, 30), (4, 3)], fill=1)
        d.rectangle((9, 2, 21, 12), fill=0)
        d.rectangle((9, 19, 23, 28), fill=0)
        for x in (11, 16, 21):
            d.line((x, 4, x, 9), fill=1, width=2)
    else:
        d.ellipse((2, 2, 30, 30), outline=1, width=3)
        d.line((16, 7, 16, 17, 23, 21), fill=1, width=3)
    icons[name] = im

header = ['// Original NeoGuard pictograms; generated by assets/build_assets.py.',
          '#pragma once', '#include <Arduino.h>', '']
for name, im in icons.items():
    for size in (16, 32):
        bitmap = im.resize((size, size), Image.Resampling.NEAREST)
        data = []
        for y in range(size):
            for x in range(0, size, 8):
                data.append(sum((1 << (7 - bit)) for bit in range(8)
                                if bitmap.getpixel((x + bit, y))))
        header.append(f'const uint8_t ICON_{name.upper()}_{size}[] PROGMEM = {{')
        for offset in range(0, len(data), 12):
            header.append('  ' + ', '.join(f'0x{b:02X}' for b in data[offset:offset+12]) + ',')
        header.extend(['};', ''])
    paths = ''.join(f'<rect x="{x}" y="{y}" width="1" height="1"/>'
                    for y in range(32) for x in range(32) if im.getpixel((x, y)))
    (ROOT / f'{name}.svg').write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><g fill="currentColor">{paths}</g></svg>\n',
        encoding='utf-8')
(ROOT.parent / 'display_icons.h').write_text('\n'.join(header), encoding='utf-8')

# Illustration only. Firmware always obtains values from the sensors/RTC.
BG, PANEL, WHITE, MUTED = '#081522', '#10283B', '#EAF5FF', '#90ADC1'
RED, CYAN, GOLD, GREEN = '#FF607B', '#54D3EF', '#FFC76A', '#6AD5AA'
preview = Image.new('RGB', (240, 280), BG)
d = ImageDraw.Draw(preview)
font_file = Path('C:/Windows/Fonts/consola.ttf')
def text(x, y, value, size=10, color=WHITE):
    d.text((x, y), value, font=ImageFont.truetype(str(font_file), size), fill=color)
def icon(name, x, y, size, color):
    mask = icons[name].resize((size, size), Image.Resampling.NEAREST).convert('L')
    preview.paste(color, (x, y, x+size, y+size), mask)

